CREATE TABLE statements
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id          BIGINT      NOT NULL REFERENCES accounts (id),
    statement_date      DATE        NOT NULL,
    opening_balance_minor BIGINT    NOT NULL,
    closing_balance_minor BIGINT    NOT NULL,
    deposits_minor      BIGINT      NOT NULL,
    withdrawals_minor   BIGINT      NOT NULL,
    transfers_in_minor  BIGINT      NOT NULL,
    transfers_out_minor BIGINT      NOT NULL,
    entry_count         BIGINT      NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT uk_statements_account_date
        UNIQUE (account_id, statement_date),
    CONSTRAINT ck_statements_non_negative
        CHECK (opening_balance_minor >= 0
            AND closing_balance_minor >= 0
            AND deposits_minor >= 0
            AND withdrawals_minor >= 0
            AND transfers_in_minor >= 0
            AND transfers_out_minor >= 0
            AND entry_count >= 0)
);

CREATE INDEX idx_statements_account_id ON statements (account_id);

CREATE TABLE usd_khr_rate
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rate_minor       BIGINT      NOT NULL,
    effective_from   DATE        NOT NULL,
    set_by_user_id   BIGINT      REFERENCES users (id),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT uk_usd_khr_rate_effective_from UNIQUE (effective_from),
    CONSTRAINT ck_usd_khr_rate_positive CHECK (rate_minor > 0)
);

