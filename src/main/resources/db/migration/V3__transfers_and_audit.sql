CREATE TABLE transactions
(
    id                            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                       BIGINT       NOT NULL REFERENCES users (id),
    idempotency_key               VARCHAR(100) NOT NULL,
    transaction_type              VARCHAR(20)  NOT NULL,
    source_account_id             BIGINT       NOT NULL REFERENCES accounts (id),
    destination_account_id        BIGINT       NOT NULL REFERENCES accounts (id),
    amount_minor                  BIGINT       NOT NULL,
    currency                      VARCHAR(3)   NOT NULL,
    source_balance_after_minor    BIGINT       NOT NULL,
    destination_balance_after_minor BIGINT     NOT NULL,
    created_at                    TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uk_transactions_user_idempotency
        UNIQUE (user_id, idempotency_key),
    CONSTRAINT ck_transactions_amount_positive
        CHECK (amount_minor > 0),
    CONSTRAINT ck_transactions_transaction_type
        CHECK (transaction_type IN ('TRANSFER')),
    CONSTRAINT ck_transactions_accounts_differ
        CHECK (source_account_id <> destination_account_id),
    CONSTRAINT ck_transactions_currency
        CHECK (currency IN ('USD', 'KHR'))
);

CREATE INDEX idx_transactions_source_account_id ON transactions (source_account_id);
CREATE INDEX idx_transactions_destination_account_id ON transactions (destination_account_id);

ALTER TABLE ledger_entries
    ADD COLUMN transaction_id BIGINT REFERENCES transactions (id),
    DROP CONSTRAINT ck_ledger_entries_entry_type,
    DROP CONSTRAINT ck_ledger_entries_type_sign;

ALTER TABLE ledger_entries
    ADD CONSTRAINT ck_ledger_entries_entry_type
        CHECK (entry_type IN ('DEPOSIT', 'WITHDRAWAL', 'TRANSFER_IN', 'TRANSFER_OUT')),
    ADD CONSTRAINT ck_ledger_entries_type_sign
        CHECK ((entry_type IN ('DEPOSIT', 'TRANSFER_IN') AND amount_minor > 0)
            OR (entry_type IN ('WITHDRAWAL', 'TRANSFER_OUT') AND amount_minor < 0)),
    ADD CONSTRAINT ck_ledger_entries_transfer_link
        CHECK ((entry_type IN ('TRANSFER_IN', 'TRANSFER_OUT') AND transaction_id IS NOT NULL)
            OR (entry_type IN ('DEPOSIT', 'WITHDRAWAL') AND transaction_id IS NULL));

CREATE INDEX idx_ledger_entries_transaction_id ON ledger_entries (transaction_id);

CREATE TABLE audit_log
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT      NOT NULL REFERENCES users (id),
    action        VARCHAR(50) NOT NULL,
    entity_type   VARCHAR(50) NOT NULL,
    entity_id     BIGINT,
    detail        VARCHAR(500),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_audit_log_actor_user_id ON audit_log (actor_user_id);
CREATE INDEX idx_audit_log_entity ON audit_log (entity_type, entity_id);

CREATE FUNCTION reject_audit_log_mutation() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    RAISE EXCEPTION 'audit_log is append-only'
        USING ERRCODE = 'integrity_constraint_violation';
END;
$$;

CREATE TRIGGER trg_audit_log_no_update_or_delete
    BEFORE UPDATE OR DELETE
    ON audit_log
    FOR EACH ROW
EXECUTE FUNCTION reject_audit_log_mutation();

CREATE TRIGGER trg_audit_log_no_truncate
    BEFORE TRUNCATE
    ON audit_log
    FOR EACH STATEMENT
EXECUTE FUNCTION reject_audit_log_mutation();
