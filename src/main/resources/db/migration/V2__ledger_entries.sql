CREATE TABLE ledger_entries
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id   BIGINT      NOT NULL,
    amount_minor BIGINT      NOT NULL,
    entry_type   VARCHAR(20) NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_ledger_entries_account
        FOREIGN KEY (account_id) REFERENCES accounts (id),
    CONSTRAINT ck_ledger_entries_amount_non_zero
        CHECK (amount_minor <> 0),
    CONSTRAINT ck_ledger_entries_entry_type
        CHECK (entry_type IN ('DEPOSIT', 'WITHDRAWAL')),
    CONSTRAINT ck_ledger_entries_type_sign
        CHECK ((entry_type = 'DEPOSIT' AND amount_minor > 0)
            OR (entry_type = 'WITHDRAWAL' AND amount_minor < 0))
);

CREATE INDEX idx_ledger_entries_account_id ON ledger_entries (account_id);
